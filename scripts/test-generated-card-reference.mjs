import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
process.env.TS_NODE_COMPILER_OPTIONS = JSON.stringify({ module: 'CommonJS', moduleResolution: 'node' });
require('ts-node/register/transpile-only');
const { presentCompactContent } = require('../src/game-core/contentPresentation.ts');
const { compileCompactEffectList } = require('../src/game-core/compactEffectDsl.ts');
const { effectProgramToDisplayTags } = require('../src/game-core/effectDisplay.ts');
const { renderStatusReferences } = require('../src/shared/statusReference.ts');
const leaf = { id: 'leaf', name: '碎片<一>', emoji: '🔪', type: 'Attack', rarity: 'Common', cost: 0, description: '并不代表实际伤害的叙述', effects: { damage: 4 }, unique: false };
const child = { id: 'child', name: '刀轮碎片', emoji: '🔪', type: 'Skill', rarity: 'Common', cost: 0, description: '一圈碎刃', effects: { add_card: leaf.id }, unique: false };
const parent = { id: 'parent', name: '刀轮转生', type: 'Attack', rarity: 'Legendary', cost: 2,
  effects: [{ damage: 4, hits: 2 }, { add_card: child.id, count: 2 }], creates: [child, leaf] };
const before = structuredClone(parent);
const references = [];
const presentation = presentCompactContent(parent, 'card', { inlineStatusDetails: false, onSummonReference: ref => references.push(ref) });
assert.equal(references.length, 1, 'one collection callback per textual preview, not duplicated by groups');
assert.equal(references[0].name, child.name);
assert.match(references[0].rules, /碎片<一>/);
assert.match(references[0].references[0].rules, /4点伤害/);
assert.doesNotMatch(references[0].references[0].rules, /并不代表/);
const html = renderStatusReferences(presentation.rulesText, references);
assert.match(html, /data-card-definition=/);
assert.match(html, /data-rule-references=/);
assert.doesNotMatch(html, /碎片<一>/);
const compiled = compileCompactEffectList(parent.effects, { creates: parent.creates });
assert.equal(compiled.ok, true, JSON.stringify(compiled));
const tags = effectProgramToDisplayTags(compiled.value);
const ref = tags.find(tag => tag.reference)?.reference;
assert.match(ref.rules, /碎片<一>/);
assert.match(ref.references[0].rules, /4点伤害/);
assert.deepEqual(parent, before, 'display does not change executable templates');
assert.deepEqual(presentCompactContent(JSON.parse(JSON.stringify(parent)), 'card'), presentCompactContent(parent, 'card'));
console.log('Generated-card references: scoped nested templates, both description chains, executable rules, escaping and save roundtrip verified.');
