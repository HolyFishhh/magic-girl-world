import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
process.env.TS_NODE_COMPILER_OPTIONS = JSON.stringify({ module: 'CommonJS', moduleResolution: 'node' });
require('ts-node/register/transpile-only');
const { BattleStateStore } = require('../src/game-core/battleState.ts');
const { convertMvuEnemies } = require('../src/fish/core/mvuBattleAdapter.ts');
const definitions = Array.from({length: 7}, (_, i) => ({id: `foe_${i}`, name: `敌人${i}`, max_hp: 20, hp: 20, max_lust: 10, lust: 0, actions: [{id:'hit', name:'攻击', weight:1, effects:[{damage:2}]}]}));
let draws = 0;
const enemies = convertMvuEnemies(definitions, () => { draws++; return .5; });
assert.equal(enemies.slice(5).every(e => e.nextAction === null), true, 'reserves must not select intentions');
const store = new BattleStateStore();
store.setEnemies(enemies.slice(0,4));
assert.deepEqual(store.getEnemies().map(e=>e.stageSlot), [1,2,3,4]);
store.updateEnemyById('foe_1', {currentHp:0});
store.removeDefeatedEnemies();
assert.deepEqual(store.getEnemies().map(e=>e.stageSlot), [1,3,4], 'survivors retain their exact slots');
store.resetGame();
store.setEnemies(enemies);
assert.equal(store.getEnemies().length,5);
assert.equal(store.getReserveEnemies().length,2);
assert.equal(store.getEnemyById('foe_5'),null, 'reserve cannot be targeted');
store.updateEnemyById('foe_5',{currentHp:1});
assert.equal(store.getReserveEnemies()[0].currentHp,20);
store.updateEnemyById('foe_2',{currentHp:0});
store.removeDefeatedEnemies();
const admitted=store.admitReserveEnemies();
assert.deepEqual(admitted.map(e=>[e.id,e.stageSlot,e.nextAction]),[['foe_5',2,null]]);
assert.deepEqual(store.getEnemies().map(e=>e.id),['foe_0','foe_1','foe_5','foe_3','foe_4']);
assert.equal(store.getReserveEnemies()[0].currentHp,20);
const restored=new BattleStateStore(JSON.parse(JSON.stringify(store.getGameState())));
assert.deepEqual(restored.getEnemies(),JSON.parse(JSON.stringify(store.getEnemies())));
assert.deepEqual(restored.getReserveEnemies(),JSON.parse(JSON.stringify(store.getReserveEnemies())));
restored.setEnemies(restored.getEnemies());
assert.equal(restored.getReserveEnemies().length,1,'queue planning does not duplicate or erase reserves');
restored.resetGame();
assert.deepEqual(restored.getReserveEnemies(),[]);
console.log('enemy formation lifecycle tests passed');

