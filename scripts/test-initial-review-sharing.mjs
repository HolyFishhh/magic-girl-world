import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
process.env.TS_NODE_COMPILER_OPTIONS=JSON.stringify({module:'CommonJS',moduleResolution:'node'});
require('ts-node/register/transpile-only');
const {mechanismAuthoringReview}=require('../src/game-core/mechanismAuthoringReview.ts');
const {initialDraftAuthoringPrompt}=require('../src/sillytavern-extension/initialDraftPrompt.ts');
const {createInitializationDesignPrompt}=require('../src/sillytavern-extension/designEngine.ts');
const guide=readFileSync('worldbook_new/2流派体系与设计方法.md','utf8').replaceAll('\r\n','\n');
const review=mechanismAuthoringReview();
assert.equal(guide.split('<!-- shared:mechanism-review -->\n')[1].split('\n<!-- /shared:mechanism-review -->')[0],review);
const input={startPrompt:'进入',config:{card:'召唤与姿态'},narrative:'已成立正文',currentStat:{},designGuidance:null};
const prompt=initialDraftAuthoringPrompt(input);
assert.equal(prompt.split(review).length,2);
assert.ok(prompt.indexOf(review)>prompt.indexOf('REQUESTED_TOWER_RULES='),'one submission review follows actual player input');
assert.ok(review.length <= 600,'review stays concise rather than accumulating examples');
assert.equal(review.split('\n').length,4);
for(const text of ['状态须有施加来源','生成牌须有生成来源','不把后一步条件套到无条件步骤','不改说明掩盖缺失'])assert.ok(review.includes(text),text);
assert.ok(!prompt.includes('DESIGN_GUIDANCE='));
for(const text of ['spawn_summon','stance','语义等价','hp 在 0..max_hp','registry.templates','未领取奖励不算开局已有','依赖敌方或后续剧情的条件可以保留'])assert.ok(prompt.includes(text),text);
const legacy=createInitializationDesignPrompt({stat_data:{battle:{cards:[]}}});
assert.ok(legacy.includes('不存在自定义注册触发器'));
assert.ok(!legacy.includes('状态、资源、触发器和引用对象必须先注册'));
const duplicated=initialDraftAuthoringPrompt({...input,designGuidance:legacy});
assert.ok(duplicated.length>prompt.length);
console.log(JSON.stringify({result:'PASS shared worldbook review reaches initial request; full DSL and AI ownership retained',requestCharacters:prompt.length,removedGenericGuidanceCharacters:duplicated.length-prompt.length}));
