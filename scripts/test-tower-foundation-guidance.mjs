import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
process.env.TS_NODE_COMPILER_OPTIONS=JSON.stringify({module:'CommonJS',moduleResolution:'node'});
require('ts-node/register/transpile-only');
require('tsconfig-paths/register');
const {createContentPack}=require('../src/game-core/contentPack.ts');
const {TOWER_ARCHETYPE_PRESETS:presets,TOWER_ARCHETYPE_CATEGORIES:categories}=require('../src/game-core/towerArchetypeCatalog.ts');
const {buildTowerArchetypePrompt}=require('../src/game-core/towerArchetypePrompt.ts');
const {buildTowerFoundationGuidance}=require('../src/game-core/towerFoundationGuidance.ts');
const {buildTowerGenerationContext}=require('../src/sillytavern-extension/towerCoordinator.ts');
const {formatTowerNodeGenerationPrompt,formatTowerOpeningGenerationPrompt}=require('../src/game-core/towerRequest.ts');
const selection=buildTowerArchetypePrompt([presets.find(p=>p.id==='summon-single-core'),presets.find(p=>p.id==='scry')]);
const card={id:'known_strike',name:'已有攻击',type:'Attack',cost:1,effects:{damage:7}};
const starterGuidance=buildTowerFoundationGuidance(createContentPack({cards:[{...card,effects:{damage:6}}]}),selection);
assert.ok(!starterGuidance.observedMechanisms.some(p=>p.id==='direct-damage'),'basic damage below 7 must not bias future generation as an owned foundation');
const pack=createContentPack({cards:[card]});
const before=JSON.stringify(pack);
const guidance=buildTowerFoundationGuidance(pack,selection);
assert.equal(guidance.catalogCount,presets.length);
assert.equal(guidance.evaluatedCount,presets.length);
assert.equal(guidance.availableMechanismFamilies.length,categories.length);
assert.deepEqual(guidance.availableMechanismFamilies.flatMap(f=>f.foundations).sort(),presets.map(p=>p.name).sort());
assert.equal(guidance.selectedPreferences.length,2);
assert.ok(guidance.selectedPreferences.every(p=>p.alreadyPresent===false),'preferences must not fabricate owned mechanics');
assert.ok(guidance.observedMechanisms.some(p=>p.id==='direct-damage'),'unselected actual mechanisms remain visible');
assert.equal(JSON.stringify(pack),before,'guidance cannot rewrite valid cards');
const mvuData={stat_data:{battle:{cards:[card]},selected_mechanics:selection}};
const context=buildTowerGenerationContext({mvuData,designSnapshot:null,designState:{lineage:{}},settings:{difficultyPercent:80},chatId:'guidance-fixture',messageId:0});
const carried=JSON.parse(context.deckBalanceContext).foundationGuidance;
assert.deepEqual(carried.selectedPreferences,guidance.selectedPreferences,'preferences survive later-node context without a design snapshot');
assert.equal(carried.evaluatedCount,presets.length);
for(const kind of ['battle','elite','boss','shop','event','treasure']) {
  const prompt=formatTowerNodeGenerationPrompt({nodeId:'fixture',requestId:'fixture',basedOnRevision:0,kind,act:2,floor:5,contentSeed:1,rewardSeed:2,difficultyMultiplier:1},context);
  assert.ok(prompt.includes('mwg.foundation-guidance/v1'),`${kind} carries local catalog guidance inside the existing request`);
  assert.ok(prompt.includes(selection.split('\n')[1].split('：')[0].slice(2)));
}
assert.ok(formatTowerOpeningGenerationPrompt({requestId:'opening',basedOnRevision:0,seed:1,act:2,context}).includes('mwg.foundation-guidance/v1'));
assert.equal(mvuData.stat_data.selected_mechanics,selection);
console.log('All catalog families, separate preferences/evidence, and later node/opening prompts preserve foundation guidance without mutation.');
