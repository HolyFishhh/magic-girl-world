import assert from 'node:assert/strict';
import {summarizeFixedOpenings} from './lib/fixed-opening-acceptance.mjs';
const ids=['a','b','c','d','e'];
const rows=ids.map(id=>({id,published:true,persisted:true,semantics:'pass',mechanismCalls:1}));
assert.equal(summarizeFixedOpenings(ids,rows).verdict,'pass');
rows[0].mechanismCalls=2;
assert.equal(summarizeFixedOpenings(ids,rows).additionalRate,.2);
assert.equal(summarizeFixedOpenings(ids,rows).verdict,'pass');
rows[1].semantics='fail';
let result=summarizeFixedOpenings(ids,rows);
assert.equal(result.published,5);assert.equal(result.completed,4);
assert.equal(result.completionRate,.8);assert.equal(result.verdict,'fail');
rows[1].semantics='unverified';
assert.equal(summarizeFixedOpenings(ids,rows).verdict,'unverified');
rows[1].semantics='pass';rows[1].mechanismCalls=2;
assert.equal(summarizeFixedOpenings(ids,rows).verdict,'fail','compatibility retries count as additional calls');
rows[1].mechanismCalls=null;
result=summarizeFixedOpenings(ids,rows);
assert.equal(result.verdict,'unverified');assert.equal(result.additionalRate,null);
assert.equal(result.observedAdditionalLowerBound,1);
rows[1].semantics='fail';
assert.equal(summarizeFixedOpenings(ids,rows).verdict,'fail','known semantic failure is not hidden by unknown counts');
assert.equal(summarizeFixedOpenings(ids,rows.slice(2)).completionRate,3/5,'fixed denominator survives missing samples');
assert.deepEqual(summarizeFixedOpenings(ids,[]).missingIds,ids);
assert.throws(()=>summarizeFixedOpenings(ids,[rows[0],rows[0]]),/duplicate/);
assert.throws(()=>summarizeFixedOpenings(ids,[{...rows[0],id:'replacement'}]),/Unknown/);
assert.throws(()=>summarizeFixedOpenings(ids,[{...rows[0],mechanismCalls:0}]),/positive/);
assert.throws(()=>summarizeFixedOpenings(ids,[{...rows[0],semantics:true}]),/verdict/);
assert.equal(result.overallProjectUsability,'unproven');
const bytes=JSON.stringify(rows);summarizeFixedOpenings(ids,rows);assert.equal(JSON.stringify(rows),bytes);
console.log('PASS fixed five-opening tally: all retries, fixed denominator, explicit semantic failures and unverified evidence; no project-level completion claim.');
