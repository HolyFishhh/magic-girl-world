import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
process.env.TS_NODE_COMPILER_OPTIONS = JSON.stringify({ module: 'CommonJS', moduleResolution: 'node' });
require('ts-node/register/transpile-only');
const { TOWER_ARCHETYPE_PRESETS: presets, TOWER_ARCHETYPE_CATEGORIES: categories, TOWER_ARCHETYPE_OPERATION_EXCLUSIONS: exclusions } = require('../src/game-core/towerArchetypeCatalog.ts');
const { ARCHETYPE_GRAPH } = require('../src/game-core/archetypeGraph.ts');
const {TOWER_ARCHETYPE_COMPOSITION_COVERAGE: compositions}=require('../src/game-core/towerArchetypeCatalog.ts');
const lines = [
  '# 爬塔流派预设目录', '',
  '<!-- Generated by node scripts/export-tower-archetype-catalog.mjs; edit src/game-core/towerArchetypeCatalog.ts. -->', '',
  `当前收录 **${categories.length} 个类别、${presets.length} 项基础机制**，覆盖现有流派图谱的 **${ARCHETYPE_GRAPH.length} 个节点**。`, '',
  '这是一份供玩家多选组合的基础机制目录。具体题材、外观、卡名和故事仍由角色及世界决定；目录不预设跨机制的捆绑获胜路线，也不限制自由填写的构筑。', '',
  '## 使用与维护', '',
  '- 两个爬塔开局入口共用此目录。可跨类别多选，搜索持续保留已选项；已选菜单可以逐项移除或清空。',
  '- 选择只更新现有卡组要求中的机制段落；浏览与筛选不会修改输入或启动游戏。别名只用于识别旧存档，不会进入生成 Prompt。',
  '- 清空保留机制段落外的自定义文字。旧版单选预设会以可见的旧版提示保留，玩家可另选基础机制；命名开局预设保存完整原文。',
  '- 维护数据源 `src/game-core/towerArchetypeCatalog.ts`：保持稳定 ID，填写名称、通俗说明、一个可独立选择的机制关注点、图谱关联与操作关联。',
  '- 二级玩法改名时把旧名称保留为别名，确保旧开局预设仍能识别；别名不可与其他玩法名称冲突。变更机制含义时新增 ID，避免将已有身份改作其他用途。',
  '- 新机制落地时，补充可独立选择的基础关注点或修订现有要求；不要把多个成熟机制包装成新的预制组合。分类只表示浏览位置，机制可关联多个图谱节点。',
  '- 图谱覆盖与操作审计属于目录维护检查，不是玩家卡组的准入门槛。程序不会根据预设强制改牌、限制数量或拒绝合法构筑。',
  '- 更新后运行 `node scripts/export-tower-archetype-catalog.mjs` 与 `node scripts/test-tower-archetype-catalog.mjs`，并验证选择、切换、清除、保存与载入。目录快照由同一数据源生成。', '',
];
for (const category of categories) {
  lines.push(`## ${category.name}`, '', category.description, '');
  for (const preset of presets.filter(p => p.category === category.id)) {
    lines.push(`### ${preset.name}`, '', preset.summary, '', `**基础关注点：** ${preset.loop.join(' → ')}`, '',
      ...preset.requirements.filter(text => !preset.loop.includes(text)).map(text => `- ${text}`), '',
      `维护 ID：\`${preset.id}\`；图谱：${preset.archetypeIds.map(id => `\`${id}\``).join('、')}；操作：${preset.operations.map(op => `\`${op}\``).join('、')}。`, '');
  }
}
lines.push('## 图谱覆盖索引', '', '| 图谱机制 | 对应流派 |', '| --- | --- |');
for (const node of ARCHETYPE_GRAPH) lines.push(`| ${node.label.replaceAll('Orb', '姿态')} | ${compositions[node.id] ? '玩家自组：'+compositions[node.id].map(id=>presets.find(p=>p.id===id).name).join(' + ') : presets.filter(p => p.archetypeIds.includes(node.id)).map(p => p.name).join('、')} |`);
lines.push('', '## 操作覆盖与范围', '', `预设覆盖 ${new Set(presets.flatMap(preset => preset.operations)).size} 个玩家可用操作，其余公共操作的范围说明：`, '');
for (const [op, reason] of Object.entries(exclusions)) lines.push(`- \`${op}\`：${reason}`);
const output = `${lines.join('\n')}\n`;
const path = 'docs/design/tower-archetype-presets.md';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw Error('流派目录已过期，请运行 node scripts/export-tower-archetype-catalog.mjs');
} else writeFileSync(path, output);
console.log(`PASS catalog documentation: ${presets.length} presets, ${categories.length} categories, ${ARCHETYPE_GRAPH.length} graph nodes`);
