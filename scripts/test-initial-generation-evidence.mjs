import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
process.env.TS_NODE_COMPILER_OPTIONS=JSON.stringify({module:'CommonJS',moduleResolution:'node'});
require('ts-node/register/transpile-only');
const {InitialGenerationEvidence}=require('../src/sillytavern-extension/initialGenerationEvidence.ts');
const evidence=new InitialGenerationEvidence();
evidence.retainChat('a');
evidence.capture('a','g1','provider-final','not JSON');
evidence.capture('a','g1','normalized-draft','{"registry":{}}');
evidence.capture('a','g1','compiled-result','{"player":{}}');
assert.deepEqual(evidence.snapshot('a').runs[0].records.map(r=>r.stage),['provider-final','normalized-draft','compiled-result']);
assert.equal(evidence.snapshot('a').runs[0].records[0].text,'not JSON','invalid final evidence retained without pretending it is a draft');
const copy=evidence.snapshot('a');copy.runs[0].records[0].text='changed';assert.equal(evidence.snapshot('a').runs[0].records[0].text,'not JSON');
assert.equal(evidence.snapshot('b'),null);
evidence.retainChat('b');evidence.capture('a','late','provider-final','stale');assert.equal(evidence.snapshot('b').runs.length,0);
evidence.capture('b','g2','provider-final','x'.repeat(64_001));
assert.equal(evidence.snapshot('b').runs[0].records[0].characters,64_001);assert.equal(evidence.snapshot('b').runs[0].records[0].text.length,64_001);assert.equal(evidence.snapshot('b').runs[0].records[0].truncated,false);
evidence.captureValidationErrors('b','g2',[{code:'INVALID',path:'player.cards',message:'bad'}]);
for(let i=0;i<9;i++)evidence.capture('b',`g${i}`,'provider-final','');
assert.equal(evidence.snapshot('b').runs.length,8);assert.equal(evidence.snapshot('b').retention.droppedRuns,1);assert.equal(evidence.snapshot('b').retention.policy,'whole-run');
const persisted=evidence.snapshot('b');const restored=new InitialGenerationEvidence();restored.retainChat('b',persisted);
assert.deepEqual(restored.snapshot('b'),persisted,'metadata history survives a refresh');
evidence.retainChat(null);assert.equal(evidence.snapshot('b'),null);
console.log('PASS full per-run final-content evidence, validation grouping, immutable snapshots, metadata restore, and whole-run-only retention.');
