import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createTavernApi,getChat} from './lib/tavern-api.mjs';
const read=label=>JSON.parse(readFileSync(`tmp/play82-${label}-v164.json`,'utf8'));
const before=read('event-open'),selected=read('event-selected'),claimed=read('event-claimed');
for(const s of [selected,claimed])assert.equal(s.chatId,before.chatId);
const a=before.root.stat_data,b=selected.root.stat_data,c=claimed.root.stat_data;
assert.equal(b.run.gold,a.run.gold+15);
assert.equal(c.run.gold,b.run.gold,'reward confirmation must not apply gold twice');
assert.equal(b.battle.core.hp,a.battle.core.hp);
assert.deepEqual(b.battle.cards,a.battle.cards,'choice grants candidate, not an extra owned card');
assert.equal(c.battle.cards.length,a.battle.cards.length+1);
for(let i=0;i<a.battle.cards.length;i++)assert.deepEqual(c.battle.cards[i],a.battle.cards[i]);
assert.equal(c.battle.cards.at(-1).id,'forgotten_page');
assert.equal(c.battle.cards.at(-1).cost,0);
assert.deepEqual(c.battle.cards.at(-1).effects,{block:3});
assert.equal(c.run.phase,'awaiting_choice');
assert.equal(c.run.nodeCounts.event,a.run.nodeCounts.event+1);
assert.deepEqual(c.run.choices.map(n=>n.id),['act-1-floor-5-col-1']);
assert.equal(c.run.nodeContent['act-1-floor-5-col-0'].phase,'abandoned','left branch, NOT recovered failure');
const disk=await getChat(await createTavernApi('http://127.0.0.1:8012/'),'魔法少女世界 0.6.6.png',claimed.chatId);
assert.deepEqual(disk[1].variables[claimed.swipeId],claimed.root);
assert.equal(disk[1].mes,claimed.message);
assert.deepEqual(disk[0].chat_metadata,claimed.metadata);
console.log('PASS sample82 event gold once, staged reward exactly once, route selection and disk; abandoned failed branch is NOT retry recovery.');
