import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createTavernApi,getChat} from './lib/tavern-api.mjs';
const read=label=>JSON.parse(readFileSync(`tmp/play82-${label}-v163.json`,'utf8'));
const listener=read('battle2-listener'),stacked=read('battle2-stacked'),won=read('battle2-victory'),settled=read('battle2-settled'),claimed=read('battle2-claimed');
const state=s=>s.root.__magic_girl_world.battle_session.state;
for(const s of [listener,stacked,won,settled])assert.equal(s.chatId,claimed.chatId);
assert.equal(state(listener).player.block,0);
assert.equal(state(stacked).player.block,1);
assert.equal(state(stacked).player.statusEffects.find(s=>s.id==='ink_stained').stacks,2);
assert.ok(!state(stacked).player.hand.some(c=>c.origin==='generated'),'apply-only template does not run on stack');
assert.equal(state(won).battleResult,'victory');
assert.equal(state(won).defeatedEnemies.find(e=>e.id==='page_borer').currentHp,0);
assert.equal(settled.root.stat_data.battle.core.hp,16);
assert.deepEqual(settled.root.stat_data.battle.items,[],'consumed item leaves long-term inventory on settlement');
const a=settled.root.stat_data,b=claimed.root.stat_data;
assert.equal(b.run.nodeCounts.battle,2);
assert.equal(b.battle.cards.length,a.battle.cards.length+1);
for(let i=0;i<a.battle.cards.length;i++)assert.deepEqual(a.battle.cards[i],b.battle.cards[i]);
assert.equal(b.battle.cards.at(-1).name,'装订加固');
assert.deepEqual(b.battle.items.map(i=>({id:i.id,count:i.count})),[{id:'page_press',count:1}]);
assert.equal(b.run.phase,'awaiting_choice');
assert.equal(b.run.nodeContent['act-1-floor-5-col-0'].phase,'failed','interrupted prefetch has NOT recovered');
const disk=await getChat(await createTavernApi('http://127.0.0.1:8012/'),'魔法少女世界 0.6.6.png',claimed.chatId);
assert.deepEqual(disk[1].variables[claimed.swipeId],claimed.root);
assert.equal(disk[1].mes,claimed.message);
assert.deepEqual(disk[0].chat_metadata,claimed.metadata);
console.log('PASS sample82 second victory, stack-vs-apply behavior, consumed-item settlement, exact selected rewards and disk; future prefetch still failed, not overall acceptance.');
