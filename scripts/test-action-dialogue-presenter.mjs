import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
process.env.TS_NODE_COMPILER_OPTIONS=JSON.stringify({module:'CommonJS',moduleResolution:'node'});
require('ts-node/register/transpile-only');
const {EnemyIntentPresenter}=require('../src/fish/ui/enemyIntentPresenter.ts');
const {TavernBattleEffectPresenter}=require('../src/fish/ui/battleEffectPresenter.ts');
const {convertMvuEnemies}=require('../src/fish/core/mvuBattleAdapter.ts');
const {compileCompactEffectList}=require('../src/game-core');
// Exercise real presentation methods; replace only their log and animation ports.
const logs=[],animations=[];
const enemy=JSON.parse(JSON.stringify(convertMvuEnemies([{id:'speaker',name:'守卫',hp:20,max_hp:20,lust:0,max_lust:100,actions:[{id:'wait',name:'观望',dialogue:'不会让你过去',effects:{wait:true}}]}],()=>0)[0]));
const intent=Object.create(EnemyIntentPresenter.prototype);
intent.addLog=(...args)=>logs.push(args);
intent.logAction=(...args)=>animations.push(['actionLog',...args]);
intent.animationManager={showEnemyActionAnimation:async(...args)=>animations.push(['enemy',...args])};
await intent.showAction(enemy.actions[0],enemy);
assert.deepEqual(logs,[['守卫：不会让你过去','action']]);
assert.equal(animations.filter(x=>x[0]==='enemy').length,1);
const compiled=compileCompactEffectList({spawn_summon:{id:'speaker_summon',name:'卫兵',emoji:'🛡',max_hp:5,actions:[{id:'wait',name:'观望',dialogue:'遵命',effects:{wait:true}}]}});
assert.equal(compiled.ok,true);
const definition=JSON.parse(JSON.stringify(compiled.value.steps[0].summon));
const effects=Object.create(TavernBattleEffectPresenter.prototype);
effects.addLog=(...args)=>logs.push(args);
effects.animationManager={playSummonAction:async(...args)=>animations.push(['summon',...args])};
await effects.showSummonAction({name:definition.name},definition.actions[0]);
assert.deepEqual(logs.at(-1),['卫兵：遵命','action']);
assert.equal(animations.filter(x=>x[0]==='summon').length,1);
const count=logs.length;
await effects.showSummonAction({name:definition.name},{...definition.actions[0],dialogue:undefined});
await intent.showAction({...enemy.actions[0],dialogue:undefined},enemy);
assert.equal(logs.length,count,'omitted dialogue must not add a blank log');
console.log('Dialogue survives compiled JSON round trips and real enemy/summon presenter methods log once; absent dialogue stays silent. Animation and log ports are isolated.');
