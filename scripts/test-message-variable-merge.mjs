import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
process.env.TS_NODE_COMPILER_OPTIONS = JSON.stringify({ module: 'CommonJS', moduleResolution: 'node' });
require('ts-node/register/transpile-only');
const { mergeMessageVariableUpdate: merge } = require('../src/runtime/messageVariableMerge.ts');
const base = { stat_data: { run: { stateRevision: 23, nodeContent: { next: { phase: 'generating', requestId: 'job' } } }, battle: { hp: 62, cards: [1,2] } } };
const action = structuredClone(base); action.stat_data.battle.hp = 58;
const complete = structuredClone(base);
complete.stat_data.run.nodeContent.next = { phase: 'ready', requestId: 'job', content: { enemies: ['fixture'] } };
const result = merge(base, action, complete);
assert.equal(result.stat_data.battle.hp, 58);
assert.deepEqual(result.stat_data.run, complete.stat_data.run);
assert.deepEqual(JSON.parse(JSON.stringify(result)), result);
assert.equal(base.stat_data.run.nodeContent.next.phase, 'generating');
const conflict = structuredClone(complete); conflict.stat_data.battle.hp = 42;
assert.throws(() => merge(base, action, conflict), /后台已更新/);
assert.equal(conflict.stat_data.battle.hp, 42);
const remove = structuredClone(base); delete remove.stat_data.battle.cards;
const changedCards = structuredClone(base); changedCards.stat_data.battle.cards.push(3);
assert.throws(() => merge(base, remove, changedCards), /后台已更新/);
assert.equal(merge(base, remove, complete).stat_data.battle.cards, undefined);
const advance = structuredClone(complete); advance.stat_data.run.stateRevision++;
assert.equal(merge(base, action, advance).stat_data.run.stateRevision, 24);
assert.deepEqual(merge(base, action, action), action);
console.log('PASS message delta merge: same-revision completion survives UI action, revision advance, atomic conflicts, removal and save roundtrip');
