import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
process.env.TS_NODE_COMPILER_OPTIONS = JSON.stringify({ module: 'CommonJS', moduleResolution: 'node' });
require('ts-node/register/transpile-only');
const { prepareModeInitialVariables } = require('../src/start/core/modeInitialVariables.ts');
const { renderStoryCharacterStatus } = require('../src/shared/storyCharacterStatus.ts');
const { buildSecondStageSemanticMvuContext } = require('../src/sillytavern-extension/mvuPromptContext.ts');
const template = JSON.parse(readFileSync('worldbook_new/变量初始化.json', 'utf8'));
const story = structuredClone(template), tower = structuredClone(template);
prepareModeInitialVariables(story, 'story');
prepareModeInitialVariables(tower, 'tower');
assert.ok(story.status.clothing && story.npcs && story.factions);
assert.ok(!tower.status.clothing && !tower.status.inventory && !tower.npcs && !tower.factions);
assert.ok(tower.battle && tower.status.profession);
story.game_mode = 'story';
story.status.clothing.upper_body = '银色披风';
story.status.inventory.push({name:'旧钥匙',description:'钟楼的钥匙'});
story.status.permanent_status.push('魔法契约');
story.status.temporary_status.push({name:'疲惫',description:'需要休息'});
story.factions.relations.push({name:'守望者', reputation:12,status:'友善',note:'曾帮助主角'});
story.npcs.guide = {name:'引路人<script>', affection:42,affection_level:'信赖',relationship:'同伴',current_action:'等待主角'};
story.game_mode_lock = {schemaVersion:1,mode:'story'};
const saved = JSON.stringify(story);
prepareModeInitialVariables(story, 'tower');
assert.equal(JSON.stringify(story),saved,'never project an existing locked player save');
const html = renderStoryCharacterStatus(JSON.parse(saved));
for(const text of ['银色披风','旧钥匙','钟楼的钥匙','魔法契约','疲惫','守望者','声望 12','友善','42','信赖','同伴']) assert.ok(html.includes(text),text);
assert.ok(html.includes('&lt;script&gt;'));assert.ok(!html.includes('<script>'));
assert.ok(!html.includes('$__META_EXTENSIBLE__$'));
assert.equal(JSON.stringify(story),saved,'rendering is read-only');
assert.deepEqual(buildSecondStageSemanticMvuContext({stat_data:story}).stat_data.npcs,story.npcs);
assert.equal(renderStoryCharacterStatus({...story, game_mode_lock:{schemaVersion:1,mode:'tower'}}),'');
console.log('PASS mode-specific new-game MVU, existing-save preservation, story UI facts and second-stage continuity');
